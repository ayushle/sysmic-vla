class SysmicRestaurant(ManipulationEnv):
    """SYSMIC 2.0 in a café with a kitchen behind it (no task: reward 0, never done).

    spawn           "bar", "table", "aisle", "kitchen", "island" or (x, y, yaw)
    items           {surface: [category, ...]}: replaces ITEMS for the surfaces given
                    (an empty list leaves that surface empty)
    bar_height, table_height, kitchen_height   tops of the bar, tables and kitchen counters (m)
    seed            same object models and placement every reset
    Other arguments are robosuite's; RoboCasa-only ones (layout_ids, style_ids) are ignored.
    """

    def __init__(self, robots, spawn="bar", items=None, bar_height=0.85, table_height=0.75,
                 kitchen_height=0.85, env_configuration="default", controller_configs=None,
                 gripper_types="default", base_types="default", initialization_noise=None,
                 use_camera_obs=False, has_renderer=False, has_offscreen_renderer=True,
                 render_camera=None, render_collision_mesh=False, render_visual_mesh=True,
                 render_gpu_device_id=-1, control_freq=20, lite_physics=True, horizon=1000,
                 ignore_done=True, hard_reset=True, camera_names="agentview", camera_heights=256,
                 camera_widths=256, camera_depths=False, camera_segmentations=None,
                 renderer="mjviewer", renderer_config=None, seed=None, layout_ids=None,
                 style_ids=None):
        self.spawn = spawn
        self.heights = dict(bar_height=bar_height, table_height=table_height,
                            kitchen_height=kitchen_height)
        self.items = dict(ITEMS, **(items or {}))
        unknown = set(self.items) - set(self.surface_rects())
        if unknown:
            raise ValueError(f"unknown surface(s) {sorted(unknown)}; "
                             f"known: {sorted(self.surface_rects())}")
        self.objects, self.obj_body_id, self._placements = {}, {}, {}
        super().__init__(
            robots=robots, env_configuration=env_configuration,
            controller_configs=controller_configs, base_types=base_types,
            gripper_types=gripper_types, initialization_noise=initialization_noise,
            use_camera_obs=use_camera_obs, has_renderer=has_renderer,
            has_offscreen_renderer=has_offscreen_renderer, render_camera=render_camera,
            render_collision_mesh=render_collision_mesh, render_visual_mesh=render_visual_mesh,
            render_gpu_device_id=render_gpu_device_id, control_freq=control_freq,
            lite_physics=lite_physics, horizon=horizon, ignore_done=ignore_done,
            hard_reset=hard_reset, camera_names=camera_names, camera_heights=camera_heights,
            camera_widths=camera_widths, camera_depths=camera_depths,
            camera_segmentations=camera_segmentations, renderer=renderer,
            renderer_config=renderer_config, seed=seed)

    # -- layout helpers ------------------------------------------------------------
    def surface_rects(self):
        """{surface: (xmin, xmax, ymin, ymax, top z)} of every surface objects can go on."""
        bh, th, kh = (self.heights[k] for k in ("bar_height", "table_height", "kitchen_height"))
        rects = {"bar": (BAR_X[0] + 0.02, BAR_X[1] - 0.02, *PICKUP_Y, bh)}
        L, W = TABLE_SIZE
        for name, (x, y, along_x) in TABLES.items():
            hx, hy = (L / 2, W / 2) if along_x else (W / 2, L / 2)
            rects[name] = (x - hx, x + hx, y - hy, y + hy, th)
        rects["pass"] = (PASS[0], PASS[1], PASS[2], PASS[3] - 0.05, kh)
        rects["island"] = (*ISLAND, kh)
        return rects

    @property
    def surfaces(self):
        return self.surface_rects()

    def spawn_pose(self):
        if isinstance(self.spawn, str):
            if self.spawn not in SPAWNS:
                raise ValueError(f"unknown spawn '{self.spawn}'; known: {', '.join(SPAWNS)}")
            return SPAWNS[self.spawn]
        x, y, yaw = self.spawn
        return float(x), float(y), float(yaw)

    # -- robosuite hooks -------------------------------------------------------------
    def _check_robot_configuration(self, robots):
        super()._check_robot_configuration(robots)

    def reward(self, action=None):
        return 0.0

    def _check_success(self):
        return False

    def _load_model(self):
        super()._load_model()
        x, y, yaw = self.spawn_pose()
        robot = self.robots[0].robot_model
        robot.set_base_xpos(np.array([x, y, 0.0]))
        robot.set_base_ori(np.array([0.0, 0.0, yaw]))
        arena = RestaurantArena(**self.heights)
        arena.set_origin([0, 0, 0])
        self._create_objects()
        self.model = ManipulationTask(mujoco_arena=arena, mujoco_robots=[robot],
                                      mujoco_objects=list(self.objects.values()))

    def _create_objects(self):
        from robocasa.models.objects.kitchen_object_utils import sample_kitchen_object
        from robocasa.models.objects.objects import MJCFObject

        self.objects, self._placements = {}, {}
        rects = self.surface_rects()
        for surface, cats in self.items.items():
            x0, x1, y0, y1, z = rects[surface]
            placed = []                        # (x, y, r) on this surface
            for i, cat in enumerate(cats):
                name = f"{surface}_{cat}_{i + 1}"
                kwargs, _ = sample_kitchen_object([cat], rng=self.rng, obj_registries=("objaverse",))
                obj = MJCFObject(name=name, **kwargs)
                r = float(obj.horizontal_radius) * 0.85
                bottom = np.asarray(obj.bottom_offset, float)
                spot = None
                for _ in range(300):
                    mx = min(r, (x1 - x0) / 2 - 0.01)
                    my = min(r, (y1 - y0) / 2 - 0.01)
                    px = self.rng.uniform(x0 + mx, x1 - mx)
                    py = self.rng.uniform(y0 + my, y1 - my)
                    if all(math.hypot(px - qx, py - qy) > r + qr + 0.01 for qx, qy, qr in placed):
                        spot = (px, py)
                        break
                if spot is None:
                    print(f"[SysmicRestaurant] no room for {cat} on {surface}; left out")
                    continue
                placed.append((*spot, r))
                yaw = self.rng.uniform(-np.pi, np.pi)
                c, s = math.cos(yaw), math.sin(yaw)
                off = np.array([c * bottom[0] - s * bottom[1], s * bottom[0] + c * bottom[1]])
                pos = np.array([spot[0] - off[0], spot[1] - off[1], z - bottom[2] + 0.004])
                self.objects[name] = obj
                self._placements[name] = (pos, np.array(_yaw_quat(yaw)))

    def _setup_references(self):
        super()._setup_references()
        self.obj_body_id = {n: self.sim.model.body_name2id(o.root_body)
                            for n, o in self.objects.items()}

    def _reset_internal(self):
        super()._reset_internal()
        for name, (pos, quat) in self._placements.items():
            self.sim.data.set_joint_qpos(self.objects[name].joints[0], np.concatenate([pos, quat]))
        self.sim.forward()


def object_positions(env):
    return {n: env.sim.data.body_xpos[i].copy() for n, i in env.obj_body_id.items()}


