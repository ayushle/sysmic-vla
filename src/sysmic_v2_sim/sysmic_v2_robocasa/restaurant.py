def _f(*v):
    return " ".join(f"{float(x):.5g}" for x in v)


def _yaw_quat(yaw):
    return (math.cos(yaw / 2), 0.0, 0.0, math.sin(yaw / 2))


def _quat_mul(a, b):
    w1, x1, y1, z1 = a
    w2, x2, y2, z2 = b
    return (w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2, w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
            w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2, w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2)


class _Builder:
    def __init__(self):
        self.geoms, self.lights, self.n = [], [], 0

    def geom(self, kind, pos=None, size=None, mat="white", solid=True, quat=None,
             fromto=None, prefix="g"):
        self.n += 1
        a = [f'name="{prefix}_{self.n}"', f'type="{kind}"', f'material="{mat}"', 'group="1"',
             'contype="1" conaffinity="1"' if solid else 'contype="0" conaffinity="0"']
        if fromto is not None:
            a.append(f'fromto="{_f(*fromto)}"')
        else:
            a.append(f'pos="{_f(*pos)}"')
        if size is not None:
            a.append(f'size="{_f(*size)}"')
        if quat is not None:
            a.append(f'quat="{_f(*quat)}"')
        self.geoms.append("<geom " + " ".join(a) + "/>")

    def box(self, x0, x1, y0, y1, z0, z1, mat, solid=True, prefix="g"):
        """Axis-aligned box from its extents."""
        self.geom("box", ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2),
                  ((x1 - x0) / 2, (y1 - y0) / 2, (z1 - z0) / 2), mat, solid, prefix=prefix)

    # -- objects placed in a local frame (origin x, y; +x = the way it faces) ----------
    def local(self, ox, oy, yaw):
        c, s = math.cos(yaw), math.sin(yaw)
        q = _yaw_quat(yaw)

        def at(lx, ly, lz):
            return (ox + c * lx - s * ly, oy + s * lx + c * ly, lz)

        def lbox(lx, ly, lz, hx, hy, hz, mat, solid=True, pitch=0.0, prefix="g"):
            qq = q if not pitch else _quat_mul(q, (math.cos(pitch / 2), 0, math.sin(pitch / 2), 0))
            self.geom("box", at(lx, ly, lz), (hx, hy, hz), mat, solid, quat=qq, prefix=prefix)

        return at, lbox, q

    def legs(self, at, pts, z_top, mat="black", r=0.012, solid=True):
        for lx, ly, tx, ty in pts:
            self.geom("capsule", fromto=(*at(lx, ly, 0.05), *at(tx, ty, z_top)), size=(r,),
                      mat=mat, solid=solid)
            self.geom("cylinder", at(lx, ly, 0.025), (r + 0.004, 0.025), "gold", solid)

    def table(self, x, y, along_x, h):
        L, W = TABLE_SIZE
        yaw = 0.0 if along_x else math.pi / 2
        at, lbox, _ = self.local(x, y, yaw)
        lbox(0, 0, h - 0.015, L / 2, W / 2, 0.015, "tabletop", prefix="table")
        lbox(0, 0, h - 0.04, L / 2 - 0.01, W / 2 - 0.01, 0.01, "black")
        ix, iy = L / 2 - 0.08, W / 2 - 0.08
        self.legs(at, [(sx * ix, sy * iy, sx * (ix - 0.02), sy * (iy - 0.02))
                       for sx in (-1, 1) for sy in (-1, 1)], h - 0.05, r=0.018)

    def tub_chair(self, x, y, yaw):
        """Blush velvet tub chair."""
        at, lbox, q = self.local(x, y, yaw)
        self.geom("cylinder", at(0, 0, 0.45), (0.25, 0.05), "pink", quat=q, prefix="chair")
        for i in range(11):
            a = math.radians(105 + i * 15)       # arc behind the seat (local -x side)
            r = 0.235
            qa = _quat_mul(q, _yaw_quat(a))
            self.geom("box", at(r * math.cos(a), r * math.sin(a), 0.63), (0.035, 0.045, 0.17),
                      "pink", quat=qa, prefix="chair")
        self.legs(at, [(sx * 0.17, sy * 0.17, sx * 0.13, sy * 0.13)
                       for sx in (-1, 1) for sy in (-1, 1)], 0.40)

    def arm_chair(self, x, y, yaw):
        """Dark teal diamond-tufted armchair."""
        at, lbox, _ = self.local(x, y, yaw)
        lbox(0.0, 0, 0.44, 0.26, 0.27, 0.055, "teal", prefix="chair")
        lbox(-0.24, 0, 0.72, 0.05, 0.27, 0.25, "tufted", pitch=-0.15, prefix="chair")
        for sy in (-1, 1):
            lbox(-0.02, sy * 0.25, 0.58, 0.22, 0.035, 0.09, "tufted", prefix="chair")
        self.legs(at, [(sx * 0.2, sy * 0.2, sx * 0.19, sy * 0.19)
                       for sx in (-1, 1) for sy in (-1, 1)], 0.39)

    def stool(self, x, y, yaw):
        at, lbox, q = self.local(x, y, yaw)
        self.geom("cylinder", at(0, 0, 0.74), (0.19, 0.045), "pink", quat=q, prefix="stool")
        lbox(-0.16, 0, 0.92, 0.03, 0.17, 0.12, "pink", prefix="stool")
        self.legs(at, [(sx * 0.19, sy * 0.19, sx * 0.12, sy * 0.12)
                       for sx in (-1, 1) for sy in (-1, 1)], 0.70, mat="gold", r=0.011)
        for sx, sy, hx, hy in ((1, 0, 0.01, 0.15), (-1, 0, 0.01, 0.15),
                               (0, 1, 0.15, 0.01), (0, -1, 0.15, 0.01)):
            lbox(sx * 0.155, sy * 0.155, 0.30, hx, hy, 0.008, "gold", solid=False)

    def pendant(self, x, y, z=2.05):
        """White petal pendant lamp (visual only)."""
        self.geom("cylinder", fromto=(x, y, z + 0.1, x, y, WALL_H), size=(0.005,), mat="black",
                  solid=False)
        self.geom("ellipsoid", (x, y, z + 0.05), (0.24, 0.24, 0.1), "lamp", False)
        self.geom("ellipsoid", (x, y, z - 0.02), (0.16, 0.16, 0.08), "lamp", False)
        self.geom("sphere", (x, y, z - 0.05), (0.05,), "bulb", False)

    def light(self, pos, diffuse, direction=(0, 0, -1), cutoff=70, shadow=False, directional=False):
        self.lights.append(
            f'<light pos="{_f(*pos)}" dir="{_f(*direction)}" diffuse="{_f(*diffuse)}" '
            f'specular="0.15 0.15 0.15" cutoff="{cutoff}" exponent="2" '
            f'directional="{"true" if directional else "false"}" '
            f'castshadow="{"true" if shadow else "false"}"/>')


