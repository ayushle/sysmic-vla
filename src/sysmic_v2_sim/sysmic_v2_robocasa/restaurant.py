def _make_textures():
    """Write the PNG textures this scene uses into assets/restaurant/ (once)."""
    names = ["terrazzo", "botanical_0", "botanical_1", "botanical_2", "subway", "quarry",
             "tufted", "fluted"]
    if all(os.path.exists(os.path.join(TEX_DIR, n + ".png")) for n in names):
        return
    from PIL import Image, ImageDraw, ImageFilter

    os.makedirs(TEX_DIR, exist_ok=True)
    rng = np.random.default_rng(1)
    save = lambda img, n: img.save(os.path.join(TEX_DIR, n + ".png"))  # noqa: E731

    # terrazzo: warm white with chips of terracotta, black, grey, blush, ochre, sage
    size = 1024
    img = Image.new("RGB", (size, size), (238, 234, 228))
    d = ImageDraw.Draw(img)
    chips = [(184, 74, 52), (35, 33, 32), (128, 124, 120), (218, 150, 140), (204, 160, 82),
             (150, 166, 140), (96, 62, 50), (190, 186, 180)]
    weights = np.array([3, 2, 3, 2, 1, 1, 1, 3], float)
    for _ in range(1700):
        c = chips[rng.choice(len(chips), p=weights / weights.sum())]
        cx, cy = rng.uniform(0, size, 2)
        r = rng.uniform(3, 13) if rng.random() < 0.85 else rng.uniform(12, 24)
        k = rng.integers(3, 7)
        ang = np.sort(rng.uniform(0, 2 * np.pi, k))
        rad = r * rng.uniform(0.55, 1.0, k)
        pts = [(cx + a * math.cos(t), cy + a * math.sin(t)) for a, t in zip(rad, ang)]
        for ox in (-size, 0, size):          # wrap around so the texture tiles
            for oy in (-size, 0, size):
                d.polygon([(x + ox, y + oy) for x, y in pts], fill=c)
    save(img, "terrazzo")

    # botanical prints: palm fronds and leaves in red, pink and green on a dark ground
    for k in range(3):
        w, h = 320, 960
        img = Image.new("RGB", (w, h), (24, 38, 33))
        d = ImageDraw.Draw(img)
        palette = [(196, 38, 50), (232, 96, 98), (246, 176, 160), (44, 112, 64),
                   (22, 74, 48), (120, 24, 36)]
        for _ in range(16):
            c = palette[rng.integers(len(palette))]
            x0, y0 = rng.uniform(0, w), rng.uniform(h * 0.15, h)
            ang = rng.uniform(-2.4, -0.7)
            length = rng.uniform(180, 420)
            n = 22
            pts = []
            for i in range(n + 1):
                s = i / n
                a = ang + 0.9 * s * rng.choice([-1, 1]) * 0.6
                pts.append((x0 + length * s * math.cos(a), y0 + length * s * math.sin(a)))
            d.line(pts, fill=c, width=3)
            for i in range(2, n):
                (xa, ya), (xb, yb) = pts[i], pts[i + 1]
                t = math.atan2(yb - ya, xb - xa)
                leaf = 70 * (1 - i / n) + 18
                for side in (-1, 1):
                    tt = t + side * rng.uniform(0.7, 1.2)
                    tip = (xa + leaf * math.cos(tt), ya + leaf * math.sin(tt))
                    mid = (xa + 0.5 * leaf * math.cos(tt + 0.12 * side) + 4,
                           ya + 0.5 * leaf * math.sin(tt + 0.12 * side))
                    d.polygon([(xa, ya), mid, tip], fill=c)
        img = img.filter(ImageFilter.SMOOTH)
        save(img, f"botanical_{k}")

    # white subway tiles (kitchen walls): 4 x 8 tiles, offset rows
    img = Image.new("RGB", (512, 512), (176, 178, 176))
    d = ImageDraw.Draw(img)
    th, tw = 64, 128
    for r in range(512 // th):
        off = (tw // 2) * (r % 2)
        for col in range(-1, 512 // tw + 1):
            x = col * tw + off
            d.rectangle([x + 3, r * th + 3, x + tw - 3, r * th + th - 3], fill=(244, 244, 240))
    save(img, "subway")

    # quarry tiles (kitchen floor): red-brown squares, grey grout
    img = Image.new("RGB", (512, 512), (110, 104, 98))
    d = ImageDraw.Draw(img)
    for r in range(4):
        for col in range(4):
            v = rng.integers(-12, 12)
            d.rectangle([col * 128 + 4, r * 128 + 4, col * 128 + 124, r * 128 + 124],
                        fill=(150 + v, 72 + v // 2, 52 + v // 2))
    save(img, "quarry")

    # diamond-tufted velvet (teal armchairs, booth)
    img = Image.new("RGB", (256, 256), (18, 62, 62))
    d = ImageDraw.Draw(img)
    for i in range(-4, 5):
        d.line([(i * 64, 0), (i * 64 + 256, 256)], fill=(10, 40, 40), width=4)
        d.line([(i * 64 + 256, 0), (i * 64, 256)], fill=(10, 40, 40), width=4)
    save(img.filter(ImageFilter.GaussianBlur(2)), "tufted")

    # fluted light wood (bar front)
    img = Image.new("RGB", (256, 256))
    px = np.zeros((256, 256, 3), np.uint8)
    xs = np.arange(256)
    shade = 0.82 + 0.18 * np.cos((xs % 32) / 32 * 2 * np.pi)
    base = np.array([196, 150, 104])
    px[:] = (base[None, None, :] * shade[None, :, None]).clip(0, 255).astype(np.uint8)
    img = Image.fromarray(px)
    save(img, "fluted")


