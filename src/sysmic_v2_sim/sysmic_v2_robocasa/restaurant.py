def _snapshot(env, out_dir):
    """Save overview images rendered with free cameras (for checking the scene)."""
    import mujoco
    from PIL import Image

    os.makedirs(out_dir, exist_ok=True)
    m, d = env.sim.model._model, env.sim.data._data
    views = {
        "overview": dict(lookat=(5.5, 3.5, 0.5), distance=12.0, azimuth=-90, elevation=-55),
        "dining": dict(lookat=(5.0, 3.5, 0.8), distance=6.5, azimuth=-150, elevation=-22),
        "bar": dict(lookat=(1.3, 3.0, 0.9), distance=3.6, azimuth=180, elevation=-25),
        "art_wall": dict(lookat=(6.0, 6.5, 1.4), distance=5.0, azimuth=90, elevation=-10),
        "booths": dict(lookat=(9.6, 3.5, 0.8), distance=4.5, azimuth=-10, elevation=-20),
        "kitchen": dict(lookat=(3.5, -3.6, 0.8), distance=5.5, azimuth=90, elevation=-40),
        "passage": dict(lookat=(2.15, 0.2, 0.9), distance=4.0, azimuth=90, elevation=-15),
        "plan": dict(lookat=(5.5, 1.0, 0.0), distance=19.0, azimuth=-90, elevation=-89),
    }
    m.vis.global_.offwidth = max(m.vis.global_.offwidth, 1280)
    m.vis.global_.offheight = max(m.vis.global_.offheight, 720)
    r = mujoco.Renderer(m, height=720, width=1280)
    opt = mujoco.MjvOption()
    opt.geomgroup[:] = 0
    opt.geomgroup[1] = 1
    opt.sitegroup[:] = 0
    for name, v in views.items():
        cam = mujoco.MjvCamera()
        cam.type = mujoco.mjtCamera.mjCAMERA_FREE
        cam.lookat[:] = v["lookat"]
        cam.distance, cam.azimuth, cam.elevation = v["distance"], v["azimuth"], v["elevation"]
        r.update_scene(d, camera=cam, scene_option=opt)
        Image.fromarray(r.render()).save(os.path.join(out_dir, f"{name}.png"))
    r.close()
    print(f"images saved in {out_dir}")


def main():
    import argparse

    import sysmic_robocasa as S

    ap = argparse.ArgumentParser()
    ap.add_argument("--spawn", default="bar", help=f"one of {', '.join(SPAWNS)}")
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--snapshot", default=None, help="save overview images here, no viewer")
    args = ap.parse_args()

    if args.snapshot:
        env = S.make_env("SysmicRestaurant", spawn=args.spawn, seed=args.seed)
        env.reset()
        for _ in range(30):
            env.step(S.joint_action(env, {}))
        _snapshot(env, args.snapshot)
        env.close()
        return
    env = S.make_env("SysmicRestaurant", spawn=args.spawn, seed=args.seed,
                     has_renderer=True, renderer="mjviewer", render_camera=None)
    env.reset()
    for name, pos in object_positions(env).items():
        print(f"{name:22s} x={pos[0]:+.3f} y={pos[1]:+.3f} z={pos[2]:+.3f}")
    try:
        while not S.viewer_closed(env):
            env.step(S.joint_action(env, {}))
            env.render()
    except KeyboardInterrupt:
        pass
    finally:
        env.close()


if __name__ == "__main__":
    main()
