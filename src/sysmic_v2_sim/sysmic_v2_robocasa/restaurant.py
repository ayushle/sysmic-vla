def build_arena_xml(bar_height=0.85, table_height=0.75, kitchen_height=0.85):
    _make_textures()
    b = _Builder()
    W, H = ROOM
    t = 0.1

    # ---- dining room shell -------------------------------------------------------
    b.box(0, W, 0, H, -0.05, 0, "terrazzo", prefix="floor")
    b.box(-t, 0, -t, H + t, 0, WALL_H, "walnut", prefix="wall")                 # west
    b.box(W, W + t, -t, H + t, 0, WALL_H, "mint", prefix="wall")                # east
    b.box(-t, W + t, H, H + t, 0, WALL_H, "mint", prefix="wall")                # north
    b.box(-t, DOOR[0], -t, 0, 0, WALL_H, "mint", prefix="wall")                 # south, left of door
    b.box(DOOR[1], W + t, -t, 0, 0, WALL_H, "mint", prefix="wall")              # south, right of door
    b.box(DOOR[0], DOOR[1], -t, 0, 2.2, WALL_H, "mint", prefix="wall")          # over the door
    for x in DOOR:                                                               # gold door frame
        b.box(x - 0.03, x + 0.03, -t - 0.01, 0.01, 0, 2.2, "gold", False)
    b.box(DOOR[0], DOOR[1], -t - 0.01, 0.01, 2.17, 2.23, "gold", False)

    # wainscot rail and panel mouldings
    rail = 0.95
    b.box(0, W, H - 0.02, H, rail - 0.02, rail + 0.02, "mint_dark", False)
    b.box(W - 0.02, W, 0, H, rail - 0.02, rail + 0.02, "mint_dark", False)
    b.box(DOOR[1], W, 0, 0.02, rail - 0.02, rail + 0.02, "mint_dark", False)

    def frame_on_north(x0, x1, z0, z1, art=None):
        d = 0.025
        if art is not None:
            # 2D textures are projected on a box's local xy face: turn that face to the room
            b.geom("box", ((x0 + x1) / 2, H - 0.02, (z0 + z1) / 2), ((x1 - x0) / 2, (z1 - z0) / 2,
                   0.01), art, False, quat=(math.cos(math.pi / 4), math.sin(math.pi / 4), 0, 0))
        for (a0, a1, c0, c1) in ((x0 - d, x1 + d, z0 - d, z0), (x0 - d, x1 + d, z1, z1 + d),
                                 (x0 - d, x0, z0, z1), (x1, x1 + d, z0, z1)):
            b.box(a0, a1, H - 0.04, H, c0, c1, "frame" if art else "mint_dark", False)

    x = 3.0
    k = 0
    while x + 0.55 < W - 0.4:
        frame_on_north(x, x + 0.5, 1.1, 2.7, f"art{k % 3}")
